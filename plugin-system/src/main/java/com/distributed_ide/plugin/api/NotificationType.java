package com.distributed_ide.plugin.api;

/**
 * Types of notifications that can be shown to users.
 */
public enum NotificationType {
    /**
     * Informational notification.
     */
    INFO,
    
    /**
     * Success notification.
     */
    SUCCESS,
    
    /**
     * Warning notification.
     */
    WARNING,
    
    /**
     * Error notification.
     */
    ERROR
}
